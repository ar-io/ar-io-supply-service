// Account byte offsets (Codama struct layouts from @ar.io/solana-contracts).
// SPL Mint: [4 mintAuthorityOption][32 mintAuthority][u64 supply]...
const OFF_MINT_SUPPLY = 36;
// ArioConfig: [8 disc][32 authority][32 mint][32 arns][32 treasury][u64 total]...
// (`total` @136 is the frozen genesis declaration — see the TOTAL note above;
// we read supply from the mint instead.)
const OFF_CONFIG_CIRCULATING = 152;
const OFF_CONFIG_LOCKED = 160;
// GatewaySettings: protocolTokenAccount@189; counters after arnsProgramId@221.
const OFF_GAR_TOTAL_STAKED = 253;
const OFF_GAR_TOTAL_DELEGATED = 261;
const OFF_GAR_TOTAL_WITHDRAWN = 269;
// SPL token account: [32 mint][32 owner][u64 amount]
const OFF_TOKEN_AMOUNT = 64;

export interface DecodedSupply {
  total: number;
  circulating: number;
  locked: number;
  staked: number;
  delegated: number;
  withdrawn: number;
  protocolBalance: number;
}

/** Final response shape, denominated in ARIO (not mARIO). */
export interface SupplyResponse {
  total: number;
  circulating: number;
  locked: number;
  staked: number;
  delegated: number;
  withdrawn: number;
  protocolBalance: number;
  liquid: number;
}

/**
 * Portable little-endian u64 read. ARIO supply caps at 1B * 1e6 ≈ 2^50, well
 * under Number.MAX_SAFE_INTEGER, so a Number is exact.
 */
export function readU64LE(buf: Buffer, offset: number): number {
  let value = 0n;
  for (let i = 7; i >= 0; i--) {
    value = (value << 8n) | BigInt(buf[offset + i]);
  }
  return Number(value);
}

interface RawAccounts {
  mint: Buffer;
  config: Buffer;
  gar: Buffer;
  token: Buffer;
}

/**
 * Atomically fetch the four fixed accounts (same slot) via a single
 * getMultipleAccounts JSON-RPC call, returning decoded Buffers.
 */
export async function fetchSupplyAccounts(
  rpcUrl: string,
  signal: AbortSignal,
): Promise<RawAccounts> {
  const response = await fetch(rpcUrl, {
    method: "POST",
    signal,
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: 1,
      method: "getMultipleAccounts",
      params: [
        [ARIO_MINT, ARIO_CONFIG_PDA, GAR_SETTINGS_PDA, PROTOCOL_TOKEN_ACCOUNT],
        { encoding: "base64", commitment: "confirmed" },
      ],
    }),
  });

  if (!response.ok) {
    throw new Error(`Solana RPC error: ${response.statusText}`);
  }

  const json = (await response.json()) as {
    error?: unknown;
    result?: { value?: Array<{ data: [string, string] } | null> };
  };
  if (json.error) {
    throw new Error(`Solana RPC error: ${JSON.stringify(json.error)}`);
  }

  const values = json.result?.value;
  if (!Array.isArray(values) || values.length !== 4) {
    throw new Error("Unexpected getMultipleAccounts response shape");
  }

  const addresses = [
    ARIO_MINT,
    ARIO_CONFIG_PDA,
    GAR_SETTINGS_PDA,
    PROTOCOL_TOKEN_ACCOUNT,
  ];
  const [mint, config, gar, token] = values.map((v, i) => {
    if (!v) {
      throw new Error(`Account ${addresses[i]} not found`);
    }
    return Buffer.from(v.data[0], "base64");
  });

  return { mint, config, gar, token };
}

/**
 * Decode the on-chain supply buckets (mARIO) from the four accounts.
 *
 * `total` is the mint's live `supply`, so it reflects holder burns — NOT the
 * frozen ArioConfig.total_supply declaration (see the TOTAL note at the top).
 * `protocolBalance` is the live reward-reserve token-account balance — NOT
 * the folded ArioConfig.protocol_balance accounting field, which
 * double-counts the staking buckets.
 */
export function decodeSupply({
  mint,
  config,
  gar,
  token,
}: RawAccounts): DecodedSupply {
  // Defensive: a program upgrade that changes account layout would shift
  // these offsets; require the accounts to be at least as large as the
  // fields we read.
  if (mint.length < OFF_MINT_SUPPLY + 8) {
    throw new Error(`ARIO mint too small (${mint.length}B)`);
  }
  if (config.length < OFF_CONFIG_LOCKED + 8) {
    throw new Error(`ArioConfig too small (${config.length}B)`);
  }
  if (gar.length < OFF_GAR_TOTAL_WITHDRAWN + 8) {
    throw new Error(`GatewaySettings too small (${gar.length}B)`);
  }
  if (token.length < OFF_TOKEN_AMOUNT + 8) {
    throw new Error(`Protocol token account too small (${token.length}B)`);
  }

  return {
    total: readU64LE(mint, OFF_MINT_SUPPLY),
    circulating: readU64LE(config, OFF_CONFIG_CIRCULATING),
    locked: readU64LE(config, OFF_CONFIG_LOCKED),
    staked: readU64LE(gar, OFF_GAR_TOTAL_STAKED),
    delegated: readU64LE(gar, OFF_GAR_TOTAL_DELEGATED),
    withdrawn: readU64LE(gar, OFF_GAR_TOTAL_WITHDRAWN),
    protocolBalance: readU64LE(token, OFF_TOKEN_AMOUNT),
  };
}

/**
 * Plausibility checks to catch a layout drift (program upgrade, or an SPL Mint
 * layout change under `total`) before we serve garbage to price aggregators.
 * Deliberately loose — a real layout error yields wildly out-of-range or
 * negative numbers, not a fraction-of-a-percent gap, so ordinary holder burns
 * pass through untouched while a misread offset trips the range check.
 */
export function assertPlausible(supply: DecodedSupply): void {
  const { total } = supply;
  if (
    !(
      total > 900_000_000 * MARIO_PER_ARIO &&
      total < 1_100_000_000 * MARIO_PER_ARIO
    )
  ) {
    throw new Error(`Implausible total supply: ${total} mARIO`);
  }
  for (const key of [
    "circulating",
    "locked",
    "staked",
    "delegated",
    "withdrawn",
    "protocolBalance",
  ] as const) {
    const v = supply[key];
    if (!(v >= 0 && v <= total)) {
      throw new Error(`Implausible ${key}: ${v} mARIO`);
    }
  }
}

/** Sum of pre-cutoff vault buckets that have not unlocked yet, as of `now`. */
export function lockedBeforeCutoff(now: number, buckets: LockBucket[] = PRE_CUTOFF_LOCK_BUCKETS): number {
  return buckets.reduce(
    (sum, bucket) => (bucket.endTimestamp > now ? sum + bucket.balance : sum),
    0,
  );
}

/**
 * Fetch, decode, sanity-check, and shape the full supply response
 * (denominated in ARIO). Throws on any failure — caller decides whether to
 * fall back to a cached value.
 */
export async function getSupply(rpcUrl: string, signal: AbortSignal): Promise<SupplyResponse> {
  const accounts = await fetchSupplyAccounts(rpcUrl, signal);
  const supplyData = decodeSupply(accounts);
  assertPlausible(supplyData);

  const now = Date.now();
  const locked = lockedBeforeCutoff(now);

  const mario = {
    ...supplyData,
    // Circulating excludes only the pre-cutoff vesting vaults still locked.
    circulating: supplyData.total - locked,
    // Liquid is the strict on-chain circulating (freely transferable) balance.
    liquid: supplyData.circulating,
  };

  // convert the values to be denominated in ARIO (from mARIO)
  return Object.fromEntries(
    Object.entries(mario).map(([key, value]) => [key, value / MARIO_PER_ARIO]),
  ) as unknown as SupplyResponse;
}
