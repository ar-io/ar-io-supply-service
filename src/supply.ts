//! AR.IO token supply: fetch + decode + sanity-check.
//!
//! The AR.IO network migrated from AO to Solana. This module reads live
//! supply straight from Solana (native fetch JSON-RPC, no SDK dependency)
//! by reading four FIXED, immutable accounts:
//!
//!   - ARIO SPL mint        -> total supply (live, tracks burns)
//!   - ArioConfig PDA       -> circulating(liquid) / locked supply
//!   - GatewaySettings PDA  -> staked / delegated / withdrawn counters
//!   - protocol token acct  -> live reward-reserve balance (protocolBalance)
//!
//! Account addresses, byte offsets, and the pre-cutoff vault snapshot are
//! regenerated by scripts/gen-supply-snapshot.mts in the ar-io-sdk repo.
//!
//! TOTAL — read from the mint, NOT from ArioConfig:
//!   `ArioConfig.total_supply` is a genesis DECLARATION, written once by
//!   `finalize_supply` and never updated. ARIO is a standard SPL token, so any
//!   holder can burn their own tokens — two holders have already done so via a
//!   wallet-cleanup incinerator, putting real supply 373.297318 ARIO below the
//!   1B declaration. The mint's own `supply` field tracks every burn (and any
//!   future mint) in real time, so it is the only correct source for a number
//!   that price aggregators consume. Note `finalize_migration` permanently
//!   disables `finalize_supply`, after which the declaration can NEVER be
//!   corrected — one more reason not to depend on it.
//!
//! CIRCULATING — historical metric preserved across the migration:
//!   Migration RESET every Solana vault's startTimestamp, destroying the
//!   on-chain Dec-8-2025 cutoff signal. But the pre-cutoff vaults are
//!   balance-immutable, so their locked amounts + unlock dates are
//!   snapshotted from AO below (PRE_CUTOFF_LOCK_BUCKETS). At runtime we sum
//!   the buckets that haven't unlocked yet and report
//!   circulating = total - lockedBeforeCutoff, exactly as the AO handler
//!   did. `liquid` remains the strict on-chain circulating balance.

